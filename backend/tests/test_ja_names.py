"""Checked-in Japanese name tables (`dashboard/locales/ja/data.json`).

The tables are generated by ``scripts/gen_names_ja.py`` from a HunterPie
checkout, which CI does not have. These tests guard the committed result
instead: coverage against both ID catalogs, genuine Japanese text, and the
hand-maintained awards block surviving regeneration.
"""
import json
from pathlib import Path

from app.abnormalities import ABNORMALITY_NAMES

REPO_ROOT = Path(__file__).resolve().parents[2]
DATA_PATH = REPO_ROOT / "dashboard" / "locales" / "ja" / "data.json"
MONSTER_NAMES_PATH = REPO_ROOT / "backend" / "app" / "data" / "wilds_monster_names.json"


def _text() -> str:
    return DATA_PATH.read_text(encoding="utf-8")


def _data() -> dict:
    return json.loads(_text())


def _has_non_ascii(value: str) -> bool:
    return any(ord(char) > 0x7F for char in value)


def _duplicate_keys(pairs):
    seen = set()
    duplicates = []
    for key, _ in pairs:
        if key in seen:
            duplicates.append(key)
        seen.add(key)
    return duplicates


def test_file_is_canonical_json():
    """Sorted keys, 2-space indent, unescaped Japanese, trailing newline."""
    text = _text()

    assert text == json.dumps(
        json.loads(text), ensure_ascii=False, indent=2, sort_keys=True
    ) + "\n"


def test_no_duplicate_keys():
    """JSON object keys are unique, so no entry silently shadows another."""
    duplicates = json.loads(_text(), object_pairs_hook=_duplicate_keys)

    assert duplicates == []


def test_top_level_shape():
    """Exactly the three tables the dashboard imports."""
    data = _data()

    assert set(data) == {"monsters", "abnormalities", "awards"}
    assert all(isinstance(table, dict) for table in data.values())


def test_monsters_cover_every_catalog_id():
    """Every Wilds monster id resolves to a name."""
    monsters = _data()["monsters"]
    expected = json.loads(MONSTER_NAMES_PATH.read_text(encoding="utf-8"))

    assert len(expected) == 35
    assert set(monsters) == set(expected)


def test_monster_names_are_japanese_and_not_english():
    """Values are non-empty Japanese, never a copy of the English name."""
    monsters = _data()["monsters"]
    english = json.loads(MONSTER_NAMES_PATH.read_text(encoding="utf-8"))

    for monster_id, name in monsters.items():
        assert name.strip(), f"monster {monster_id} has a blank name"
        assert _has_non_ascii(name), f"monster {monster_id} is not Japanese: {name!r}"
        assert name != english[monster_id], f"monster {monster_id} kept English {name!r}"

    assert len(set(monsters.values())) == len(monsters)


def test_abnormalities_cover_every_display_name():
    """Every short id the backend can display has a Japanese label."""
    abnormalities = _data()["abnormalities"]

    missing = sorted(set(ABNORMALITY_NAMES) - set(abnormalities))
    assert missing == [], f"unmapped abnormality ids: {missing}"


def test_abnormality_names_are_japanese():
    """Values are non-empty, Japanese, and never equal to the English label."""
    abnormalities = _data()["abnormalities"]

    for short_id, name in abnormalities.items():
        assert name.strip(), f"abnormality {short_id} has a blank name"
        assert _has_non_ascii(name), f"abnormality {short_id} is not Japanese: {name!r}"
        assert name != ABNORMALITY_NAMES.get(short_id), (
            f"abnormality {short_id} kept English {name!r}"
        )


def test_awards_block_is_present():
    """Awards stay hand-maintained: id -> name, complete or empty.

    Empty until the native reviewer supplies the 30 in-game names; a partial
    table would silently mix languages, so it must be all-or-nothing.
    """
    awards = _data()["awards"]

    assert isinstance(awards, dict)
    assert all(isinstance(key, str) and isinstance(value, str) for key, value in awards.items())
    assert len(awards) in (0, 30), f"awards table has {len(awards)} entries; expected 0 or 30"
    assert all(value.strip() and _has_non_ascii(value) for value in awards.values())
